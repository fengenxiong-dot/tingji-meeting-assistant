import { createApp } from '../server.js';
import { mkdtempSync,writeFileSync,rmSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { wavHeader } from '../lib/store.js';
const dir=mkdtempSync(path.join(os.tmpdir(),'tingjijun-ui-'));
const app=createApp({dataDir:dir,settingsOverride:{asrKey:'',llmKey:'',asrUrl:'https://openrouter.ai/api/v1',asrModel:'test',llmUrl:'https://openrouter.ai/api/v1',llmModel:'test',fastMode:true}});
const r=app.store.create({title:'界面验收记录（测试数据）'});
app.store.segment(r.id,0,2,'我们决定下周交付，报价十二万元。');
app.store.summary(r.id,'## 会议摘要\n讨论了交付与报价。\n\n### 关键结论\n- **下周交付**\n- 报价 **十二万元**\n\n## 待办事项\n1. 确认交付日期\n\n<script>alert(1)</script><img src=x onerror=alert(1)>');
app.store.update(r.id,{status:'complete',duration:2,participants:'测试参与人'});
writeFileSync(app.store.audioPath(r.id),Buffer.concat([wavHeader(64000),Buffer.alloc(64000)]));
const interview=app.store.create({title:'前端工程师面试（测试数据）',scenario:'interview'});
app.store.segment(interview.id,0,2,'问题：介绍一个你负责的前端项目。回答：负责过订单系统的性能优化。');
app.store.event(interview.id,'pause',2);
app.store.event(interview.id,'resume',2);
app.store.summary(interview.id,'## 核心问答记录\n- 问题：介绍一个你负责的前端项目。\n- 回答要点：订单系统性能优化。\n\n## 初步评价\n- 专业基础：有实际项目经验，其他维度暂无足够信息。','final',2);
app.store.update(interview.id,{status:'complete',duration:2,participants:'候选人 A'});
writeFileSync(app.store.audioPath(interview.id),Buffer.concat([wavHeader(64000),Buffer.alloc(64000)]));
console.log(await app.listen(4318));
process.on('SIGINT',async()=>{await app.close();rmSync(dir,{recursive:true,force:true});process.exit();});
